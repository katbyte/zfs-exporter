#!/usr/bin/env bash
#
# Regenerates the source-build formula in katbyte/homebrew-tap for a released tag.
# Usage: TAG=v1.0.0 [TAP_DRY_RUN=1] HOMEBREW_TAP_GITHUB_TOKEN=... ./.scripts/update-homebrew-formula.sh
set -euo pipefail

TAG="${TAG:?set TAG to the release tag, e.g. v1.0.0}"

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

echo "==> fetching source tarball for ${TAG}..."
curl -sSfL "https://github.com/katbyte/zfs-exporter/archive/refs/tags/${TAG}.tar.gz" -o "$tmp/src.tar.gz"

# GitHub answers some missing tarballs with a web page rather than an error, and its hash would make a formula that never installs
tar -tzf "$tmp/src.tar.gz" > /dev/null 2>&1 || { echo "==> ${TAG} has no source tarball on GitHub yet" >&2; exit 1; }
SHA256="$(sha256sum "$tmp/src.tar.gz" | cut -d' ' -f1)"

cat > "$tmp/zfs-exporter.rb" <<FORMULA
# typed: false
# frozen_string_literal: true

# This file is generated by the zfs-exporter release workflow - do not edit by hand.
class ZfsExporter < Formula
  desc "How long a Linux machine's ZFS pools, vdevs and disks take to answer, for Prometheus"
  homepage "https://github.com/katbyte/zfs-exporter"
  url "https://github.com/katbyte/zfs-exporter/archive/refs/tags/${TAG}.tar.gz"
  sha256 "${SHA256}"
  license "GPL-3.0-only"
  head "https://github.com/katbyte/zfs-exporter.git", branch: "main"

  depends_on "go" => :build
  # it runs ZFS's programs on Linux and reads the Linux kernel's /sys, so on any other system it would find nothing to report
  depends_on :linux

  def install
    system "go", "build", *std_go_args(ldflags: "-s -w -X github.com/katbyte/go-kt/version.Version=${TAG} -X github.com/katbyte/go-kt/version.GitCommit=homebrew")
  end

  test do
    assert_match "${TAG}", shell_output("#{bin}/zfs-exporter version")
  end
end
FORMULA

if [ "${TAP_DRY_RUN:-0}" = "1" ]; then
  echo "==> dry run; generated formula:"
  cat "$tmp/zfs-exporter.rb"
  exit 0
fi

: "${HOMEBREW_TAP_GITHUB_TOKEN:?set HOMEBREW_TAP_GITHUB_TOKEN to a token with push access to katbyte/homebrew-tap}"
echo "==> pushing formula to katbyte/homebrew-tap..."
git clone --depth 1 "https://x-access-token:${HOMEBREW_TAP_GITHUB_TOKEN}@github.com/katbyte/homebrew-tap.git" "$tmp/tap"
mkdir -p "$tmp/tap/Formula"
cp "$tmp/zfs-exporter.rb" "$tmp/tap/Formula/zfs-exporter.rb"
cd "$tmp/tap"
git config user.name "zfs-exporter-release"
git config user.email "zfs-exporter-release@katbyte.me"
git add Formula/zfs-exporter.rb
git diff --cached --quiet && { echo "==> formula unchanged"; exit 0; }
git commit -m "zfs-exporter ${TAG}"
git push
echo "==> done"
